def style_workbook(wb: Workbook) -> None:
    header_font = Font(name="Calibri", bold=True, color="FFFFFF", size=12)
    header_fill = PatternFill("solid", fgColor="1F4E79")
    cat_fill = PatternFill("solid", fgColor="D6E3F0")
    thin = Border(
        left=Side(style="thin", color="B0B0B0"),
        right=Side(style="thin", color="B0B0B0"),
        top=Side(style="thin", color="B0B0B0"),
        bottom=Side(style="thin", color="B0B0B0"),
    )
    wrap = Alignment(wrap_text=True, vertical="top")

    for ws in wb.worksheets:
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = f"A1:D{ws.max_row}"
        for col, width in enumerate([18, 42, 88, 14], start=1):
            ws.column_dimensions[get_column_letter(col)].width = width
        for cell in ws[1]:
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(wrap_text=True, vertical="center")
        for row in ws.iter_rows(min_row=2, max_row=ws.max_row, max_col=4):
            for idx, cell in enumerate(row):
                cell.border = thin
                cell.alignment = wrap
                if idx == 0:
                    cell.fill = cat_fill
                    cell.font = Font(bold=True)
            ws.row_dimensions[row[0].row].height = max(60, min(140, 18 * (1 + len(str(row[2].value)) // 90)))


